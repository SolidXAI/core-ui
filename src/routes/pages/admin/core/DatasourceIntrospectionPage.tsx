    updateDrawerDraft((current) => ({
      ...current,
      columns: current.columns.map((column) => {
        if (column.columnName !== columnName) return column;
        if (column.handledBySuperclass || column.isPrimaryKey) return column;
        return { ...column, include };
      }),
    }));
